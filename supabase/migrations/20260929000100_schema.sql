-- Rescue Bites schema: accounts, restaurants, menus, offers, orders, payments, credit, payouts, legal.
-- Money is stored in integer cents; rates in basis points (1 bp = 0.01%).

create extension if not exists postgis with schema extensions;
create extension if not exists citext with schema extensions;

create type public.user_role as enum ('customer', 'restaurant', 'admin');
create type public.account_status as enum ('active', 'suspended');
create type public.restaurant_status as enum ('pending', 'approved', 'suspended');
create type public.offer_status as enum ('active', 'paused', 'ended');
create type public.offer_reason as enum ('wrong_order', 'delayed_order', 'unclaimed_order', 'overproduction', 'end_of_day', 'other');
create type public.order_status as enum ('pending_payment', 'reserved', 'picked_up', 'cancelled', 'expired', 'failed');
create type public.refund_method as enum ('original', 'credit');
create type public.credit_kind as enum ('refund', 'goodwill', 'redeem', 'restore', 'adjustment');
create type public.payout_kind as enum ('transfer', 'reversal', 'manual');

-- ---------------------------------------------------------------- accounts

-- One row per Supabase Auth user. Created by the on_auth_user_created trigger.
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email extensions.citext not null unique,
  username extensions.citext not null unique check (username::text ~ '^[A-Za-z0-9_.]{3,24}$'),
  role public.user_role not null default 'customer',
  status public.account_status not null default 'active',
  stripe_customer_id text,
  created_at timestamptz not null default now()
);

-- Business settings the owner can change in the admin console.
create table public.settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);
