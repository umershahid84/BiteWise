-- Permanent bans, timed restaurant suspensions, and restaurant subscriptions.
--
-- Bans: a banned person can never log in again, and their email can't be used for a new account. A banned
-- restaurant is taken off the site for good (its owner is banned too). Admins can lift a ban made by mistake.
--
-- Restaurant suspensions now last a set number of days, like account suspensions: the every-minute sweep
-- approves the restaurant again when suspended_until passes. (Suspensions made before this have no end date and
-- last until an admin reinstates the restaurant.)
--
-- Subscriptions: restaurants pay $15 a month or $150 a year (prices are settings). The first 50 restaurants that
-- are approved are Founding Partners and use Bite Wise free for as long as they stay partners. Paid plans renew
-- automatically unless the restaurant turns auto-renewal off; the app charges the saved card (src/lib/subscriptions.ts).
-- When a renewal payment fails, the restaurant has 7 days to update its card before its plan lapses.
-- An approved restaurant needs a plan (founding or paid) to post offers.

alter table public.restaurants add column suspended_until timestamptz;

create type public.subscription_plan as enum ('founding', 'monthly', 'annual');
create type public.subscription_status as enum ('active', 'past_due', 'expired');

create table public.restaurant_subscriptions (
  restaurant_id bigint primary key references public.restaurants (id) on delete cascade,
  plan public.subscription_plan not null,
  -- The plan charged at the next renewal (a restaurant can switch between monthly and annual from then on).
  renew_plan public.subscription_plan,
  status public.subscription_status not null default 'active',
  founding_number integer unique check (founding_number > 0),
  auto_renew boolean not null default true,
  price_cents integer not null default 0 check (price_cents >= 0),
  current_period_start timestamptz,
  current_period_end timestamptz,
  customer_ref text,
  card_ref text,
  card_label text not null default '',
  last_payment_error text not null default '',
  retry_at timestamptz,
  renewing_at timestamptz,
  reminder_sent_for timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (plan = 'founding' or current_period_end is not null)
);

create table public.subscription_payments (
  id bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants (id) on delete cascade,
  plan public.subscription_plan not null,
  amount_cents integer not null check (amount_cents > 0),
  status text not null check (status in ('paid', 'failed')),
  period_start timestamptz,
  period_end timestamptz,
  invoice_number text unique,
  transaction_id text not null default '',
  card_label text not null default '',
  error text not null default '',
  created_at timestamptz not null default now()
);
create index subscription_payments_restaurant_idx on public.subscription_payments (restaurant_id, created_at desc);

