-- True when the restaurant may post offers: a Founding Partner, a paid plan that hasn't run out, or a failed
-- renewal still inside its 7-day grace period. Auto-renewing plans also get 7 days while the renewal is charged.
create function public.restaurant_plan_ok(p_restaurant_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.restaurant_subscriptions s
    where s.restaurant_id = p_restaurant_id
      and (s.plan = 'founding'
        or (s.status = 'active' and s.current_period_end + case when s.auto_renew then interval '7 days' else interval '0' end > now())
        or (s.status = 'past_due' and s.current_period_end + interval '7 days' > now()))
  );
$$;

-- Makes the restaurant a Founding Partner if it has no plan yet and one of the free spots (setting founding_spots)
-- is left. Returns its founding number, or null. Called by the app when a restaurant is approved.
create function public.claim_founding_spot(p_restaurant_id bigint) returns integer
language plpgsql security definer set search_path = public as $$
declare
  spots integer := coalesce((select (value #>> '{}')::integer from public.settings where key = 'founding_spots'), 50);
  existing public.restaurant_subscriptions;
  taken integer;
  n integer;
begin
  perform pg_advisory_xact_lock(hashtext('bitewise_founding_spots'));
  select * into existing from public.restaurant_subscriptions where restaurant_id = p_restaurant_id;
  if existing.restaurant_id is not null then
    return existing.founding_number;
  end if;
  select count(*) into taken from public.restaurant_subscriptions where founding_number is not null;
  if taken >= spots then
    return null;
  end if;
  select coalesce(max(founding_number), 0) + 1 into n from public.restaurant_subscriptions;
  insert into public.restaurant_subscriptions (restaurant_id, plan, status, founding_number, auto_renew, price_cents)
  values (p_restaurant_id, 'founding', 'active', n, false, 0);
  return n;
end;
$$;

