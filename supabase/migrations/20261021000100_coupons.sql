-- Mirrors src/lib/pricing.ts: round half up at each step.
create function public.price_quote(p_original_unit_cents integer, p_discount_pct integer, p_quantity integer, p_tax_rate_bps integer,
  p_country text, p_coupon_id bigint default null)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  c public.coupons;
  fixed boolean := coalesce((select value #>> '{}' from public.settings where key = 'service_fee_mode'), 'percent') = 'fixed';
  fee_bps integer := case when fixed then 0 else public.setting_int('service_fee_bps') end;
  unit integer := floor((p_original_unit_cents * (100 - p_discount_pct))::numeric / 100 + 0.5);
  food integer := unit * p_quantity;
  coupon_off integer := 0;
  subtotal integer;
  fee integer;
  waived integer := 0;
  fee_tax_bps integer := public.platform_tax_bps(p_country);
  food_tax integer;
  fee_tax integer;
begin
  if p_coupon_id is not null then
    select * into c from public.coupons where id = p_coupon_id;
  end if;
  coupon_off := case c.kind
    when 'fixed' then least(c.amount_cents, food)
    when 'percent' then least(food, floor((food * c.percent)::numeric / 100 + 0.5)::integer)
    else 0 end;
  subtotal := food - coupon_off;
  fee := case when fixed then coalesce(public.setting_int('service_fee_fixed_cents'), 0)
              else floor((food * fee_bps)::numeric / 10000 + 0.5)::integer end;
  if c.kind = 'no_fee' then
    waived := fee;
    fee := 0;
  end if;
  food_tax := floor((subtotal * p_tax_rate_bps)::numeric / 10000 + 0.5);
  fee_tax := floor((fee * fee_tax_bps)::numeric / 10000 + 0.5);
  return jsonb_build_object(
    'quantity', p_quantity,
    'originalUnitCents', p_original_unit_cents,
    'discountPct', p_discount_pct,
    'unitPriceCents', unit,
    'foodCents', food,
    'couponCode', coalesce(c.code, ''),
    'couponKind', c.kind,
    'couponDescription', coalesce(c.description, ''),
    'couponDiscountCents', coupon_off,
    'couponFeeWaivedCents', waived,
    'subtotalCents', subtotal,
    'savingsCents', (p_original_unit_cents - unit) * p_quantity,
    'serviceFeeBps', fee_bps,
    'serviceFeeCents', fee,
    'taxRateBps', p_tax_rate_bps,
    'foodTaxCents', food_tax,
    'serviceFeeTaxBps', fee_tax_bps,
    'serviceFeeTaxCents', fee_tax,
    'taxCents', food_tax + fee_tax,
    'totalCents', subtotal + fee + food_tax + fee_tax
  );
end;
$$;
revoke execute on function public.price_quote(integer, integer, integer, integer, text, bigint) from public, anon, authenticated;

create function public.quote_offer(p_offer_id bigint, p_quantity integer, p_coupon_code text default null)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  o public.offers := public._orderable_offer(p_offer_id, p_quantity, false);
  r public.restaurants;
  c public.coupons;
begin
  select * into r from public.restaurants where id = o.restaurant_id;
  -- Signed-in customers are also told when they've already used the coupon (checked again when the order is placed).
  c := public._coupon_for(p_coupon_code, auth.uid(), r.country);
  return public.price_quote(o.original_price_cents, o.discount_pct, p_quantity, r.tax_rate_bps, r.country, c.id);
end;
$$;

revoke execute on function public.quote_offer(bigint, integer, text) from anon;

create function public.reserve_order(p_user uuid, p_offer_id bigint, p_quantity integer, p_card_label text, p_credit_cents integer default 0, p_coupon_code text default null)
returns public.orders
language plpgsql security definer set search_path = public as $$
declare
  o public.offers := public._orderable_offer(p_offer_id, p_quantity, true);
  r public.restaurants;
  q jsonb;
  total integer;
  card integer;
  v_username text;
  v_order public.orders;
  attempts integer := 0;
  c public.coupons;
begin
  select * into r from public.restaurants where id = o.restaurant_id;
  -- Lock the customer so concurrent checkouts can't spend the same credit twice.
  select username into v_username from public.profiles where id = p_user and status = 'active' for update;
  if v_username is null then
    raise exception 'Please log in.' using errcode = 'BB403';
  end if;

  c := public._coupon_for(p_coupon_code, p_user, r.country);
  q := public.price_quote(o.original_price_cents, o.discount_pct, p_quantity, r.tax_rate_bps, r.country, c.id);
  total := (q ->> 'totalCents')::integer;
  p_credit_cents := coalesce(p_credit_cents, 0);
  if p_credit_cents < 0 then
    raise exception 'Invalid credit amount.' using errcode = 'BB400';
  end if;
  if p_credit_cents > total then
    raise exception 'You can apply at most the order total in credit.' using errcode = 'BB400';
  end if;
  if p_credit_cents > public.credit_balance(p_user) then
    raise exception 'You don''t have that much platform credit.' using errcode = 'BB409';
  end if;
  card := total - p_credit_cents;
  if card > 0 and card < 50 then
    raise exception 'The amount left for your card must be at least $0.50. Apply a little more or less credit.' using errcode = 'BB400';
  end if;
  if card > 0 and coalesce(p_card_label, '') = '' then
    raise exception 'Please choose a card for the rest of the total.' using errcode = 'BB400';
  end if;

  update public.offers set quantity_available = quantity_available - p_quantity where id = o.id;

  insert into public.orders (
    user_id, offer_id, restaurant_id, customer_username, item_title, image_url, quantity,
    unit_price_cents, original_unit_price_cents, discount_pct, subtotal_cents, service_fee_cents, service_fee_bps,
    tax_rate_bps, tax_cents, total_cents, status, card_label, pickup_end, credit_applied_cents,
    coupon_id, coupon_code, coupon_discount_cents, coupon_fee_waived_cents
  ) values (
    p_user, o.id, o.restaurant_id, v_username, o.title, o.image_url, p_quantity,
    (q ->> 'unitPriceCents')::integer, o.original_price_cents, o.discount_pct, (q ->> 'subtotalCents')::integer,
    (q ->> 'serviceFeeCents')::integer, (q ->> 'serviceFeeBps')::integer,
    r.tax_rate_bps, (q ->> 'taxCents')::integer, total, 'pending_payment',
    case when card > 0 then p_card_label else 'Platform credit' end, o.pickup_end, p_credit_cents,
    c.id, coalesce(c.code, ''), (q ->> 'couponDiscountCents')::integer, (q ->> 'couponFeeWaivedCents')::integer
  ) returning * into v_order;

  -- PINs are unique among the restaurant's open orders (enforced by a unique index).
  loop
    attempts := attempts + 1;
    begin
      insert into public.order_pins (order_id, restaurant_id, pin) values (v_order.id, r.id, public._random_pin());
      exit;
    exception when unique_violation then
      if attempts > 200 then
        raise exception 'This restaurant has too many open orders right now.' using errcode = 'BB409';
      end if;
    end;
  end loop;

  if p_credit_cents > 0 then
    insert into public.credit_ledger (user_id, amount_cents, kind, order_id, note)
    values (p_user, -p_credit_cents, 'redeem', v_order.id, 'Applied to order');
  end if;
  return v_order;
end;
$$;

revoke execute on function public.reserve_order(uuid, bigint, integer, text, integer, text) from public, anon, authenticated;
grant execute on function public.reserve_order(uuid, bigint, integer, text, integer, text) to service_role;
grant execute on function public.price_quote(integer, integer, integer, integer, text, bigint) to service_role;
grant execute on function public._coupon_for(text, uuid, text) to service_role;

-- What the restaurant sees at pickup now includes any coupon (a food discount comes off its payout).
create or replace function public._pickup_json(o public.orders) returns jsonb
language sql stable as $$
  select jsonb_build_object(
    'id', o.id, 'status', o.status, 'itemTitle', o.item_title, 'imageUrl', o.image_url, 'quantity', o.quantity,
    'unitPriceCents', o.unit_price_cents, 'subtotalCents', o.subtotal_cents, 'serviceFeeCents', o.service_fee_cents,
    'taxCents', o.tax_cents, 'totalCents', o.total_cents, 'creditAppliedCents', o.credit_applied_cents,
    'customerUsername', o.customer_username, 'createdAt', o.created_at, 'pickupEnd', o.pickup_end, 'pickedUpAt', o.picked_up_at,
    'couponCode', o.coupon_code, 'couponDiscountCents', o.coupon_discount_cents, 'couponFeeWaivedCents', o.coupon_fee_waived_cents
  );
$$;

