-- Coupons. Admins create them for their location's customers (United States or Canada) and email them out; a
-- customer enters the code at checkout. One coupon per order, and each coupon once per customer (an order that is
-- cancelled or fails gives it back).
--   no_fee:  waives the Bite Wise service fee (and its tax). Funded by Bite Wise.
--   fixed:   a set amount off the food (at most the food's price). Funded by the restaurant.
--   percent: a percentage off the food. Funded by the restaurant.
-- A food discount lowers the order's subtotal_cents (the food the restaurant is paid for) and so the restaurant's
-- share and the food's sales tax; coupon_discount_cents records it. The service fee is still worked out on the food
-- before the coupon.

create type public.coupon_kind as enum ('no_fee', 'fixed', 'percent');

create table public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z0-9-]{3,24}$'),
  kind public.coupon_kind not null,
  amount_cents integer check (amount_cents between 1 and 100000),
  percent integer check (percent between 1 and 100),
  country text not null check (country in ('US', 'CA')),
  description text not null default '' check (char_length(description) <= 300),
  expires_at timestamptz not null,
  active boolean not null default true,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  emailed_at timestamptz,
  emailed_count integer not null default 0,
  check (kind <> 'fixed' or amount_cents is not null),
  check (kind <> 'percent' or percent is not null)
);
-- Only the server reads and writes coupons (no policies).
alter table public.coupons enable row level security;

alter table public.orders
  add column coupon_id bigint references public.coupons (id) on delete set null,
  add column coupon_code text not null default '',
  add column coupon_discount_cents integer not null default 0 check (coupon_discount_cents >= 0),
  add column coupon_fee_waived_cents integer not null default 0 check (coupon_fee_waived_cents >= 0);
create index orders_coupon_idx on public.orders (coupon_id, user_id) where coupon_id is not null;

-- The coupon for a code (null when no code is given), or an error saying why it can't be used.
create function public._coupon_for(p_code text, p_user uuid, p_country text) returns public.coupons
language plpgsql stable security definer set search_path = public as $$
declare
  c public.coupons;
begin
  if coalesce(trim(p_code), '') = '' then
    return null;
  end if;
  select * into c from public.coupons where code = upper(trim(p_code));
  if c.id is null or not c.active then
    raise exception 'This coupon code isn''t valid.' using errcode = 'BB400';
  end if;
  if c.expires_at <= now() then
    raise exception 'This coupon has expired.' using errcode = 'BB400';
  end if;
  if c.country <> p_country then
    raise exception 'This coupon is for restaurants in %.', case when c.country = 'CA' then 'Canada' else 'the United States' end using errcode = 'BB400';
  end if;
  if p_user is not null and exists (
    select 1 from public.orders where user_id = p_user and coupon_id = c.id and status not in ('cancelled', 'failed')
  ) then
    raise exception 'You''ve already used this coupon.' using errcode = 'BB409';
  end if;
  return c;
end;
$$;
revoke execute on function public._coupon_for(text, uuid, text) from public, anon, authenticated;

